"""Generate a textual Part 2 report from measured artifacts, never invented scores."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from baseline import markdown_table


def load(name):
    path = ROOT / name
    return json.loads(path.read_text(encoding='utf-8')) if path.exists() else None


def run_log(runs):
    import csv
    from collections import Counter
    with (ROOT / 'labels.csv').open(encoding='utf-8', newline='') as f:
        counts = Counter(r['label'] for r in csv.DictReader(f))
    share = min(counts.values()) / sum(counts.values())
    rows = ['| Criterion | Target | Seed 42 | Seed 7 | Seed 2024 | Verdict |',
            '|---|---|---|---|---|---|']
    measures = [
        ('1. Overall accuracy', '>= 0.75', lambda r: r['accuracy'], .75),
        ('2. Minimum label F1', '>= 0.70', lambda r: min(v['f1'] for v in r['per_label'].values()), .70),
        ('3. Label shares (dataset check)', '35%-65% each', lambda r: share, .35),
        ('4. Independent human audit', '>= 17/20', lambda r: None, .85),
        ('5. Most-confident third accuracy', '>= 0.80', lambda r: r['confidence']['accuracy_most_confident_third'], .80)]
    for name, target, get, threshold in measures:
        values = [get(next(r for r in runs if r['seed'] == s)) if any(r['seed'] == s for r in runs) else None for s in (42, 7, 2024)]
        verdict = 'PENDING' if any(v is None for v in values) else ('MET' if all(v >= threshold for v in values) else 'MISSED')
        rows.append('| ' + ' | '.join([name, target] + ['pending' if v is None else f'{v:.4f}' for v in values] + [verdict]) + ' |')
    return '\n'.join(rows)


def main():
    before, after = load('results_three_seeds_before.json'), load('results_three_seeds_after.json')
    lines = ['# Part 2 measured report', '', 'Generated by scripts/report_testing.py. Missing evidence remains pending.', '']
    baseline, trained = load('baseline_results.json'), load('results.json')
    lines += ['## Baseline vs. Trained', '']
    if baseline:
        lines.append(markdown_table(baseline['scores'], list(trained['per_label']), trained))
    else:
        lines.append('Baseline pending; no comparison score is claimed.')
    for title, runs in [('Run Log — Before', before), ('Run Log — After', after)]:
        lines += ['', f'## {title}', '', run_log(runs) if runs else 'Pending execution.']
        if runs:
            spread = max(r['accuracy'] for r in runs) - min(r['accuracy'] for r in runs)
            lines += ['', f'Accuracy spread: {spread:.4f}. Device: {runs[0]["device_name"]}; torch {runs[0]["torch_version"]}.',
                      '', 'Confusion matrices: rows are true labels; columns are predictions.']
            for r in runs:
                labels = list(r['confusion'])
                lines += ['', f'### Seed {r["seed"]}', '', '| true / predicted | ' + ' | '.join(labels) + ' |', '|---|' + '---|' * len(labels)]
                for label in labels:
                    lines.append('| ' + label + ' | ' + ' | '.join(str(r['confusion'][label][p]) for p in labels) + ' |')
    lines += ['', '## Agreement Report', '',
              'Pending student annotations and TF-provided data/staff_labels.csv. No agreement rate or human adjudication is claimed. The staff running-forum taxonomy differs from this project’s CS-topic taxonomy; its disagreements cannot directly identify a CS label-pair error.', '',
              'Criterion 4 separately requires an unaided independent human audit of 20 frozen CS posts. The staff exercise cannot substitute for it. Criterion 3 is a dataset property repeated for context, not three independent experiments.']
    (ROOT / 'TESTING_REPORT.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
